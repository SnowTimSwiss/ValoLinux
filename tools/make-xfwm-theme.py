#!/usr/bin/env python3
"""Generate the "ValoLinux" xfwm4 window theme: flat, light title bar with wide
minimise / maximise / close buttons (close turns red on hover), similar in spirit
to Windows 11 but drawn from scratch.

Usage: python3 -I tools/make-xfwm-theme.py [output-dir]
"""
import pathlib
import sys

from PIL import Image, ImageDraw

OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "image/config/includes.chroot/usr/share/themes/ValoLinux/xfwm4")

H = 34          # title bar height
BW = 46         # button width
BORDER = 4      # left/right/bottom frame
TITLE = {"active": (255, 255, 255), "inactive": (243, 243, 243)}
EDGE = {"active": (200, 200, 208), "inactive": (214, 214, 220)}   # 1px outline
GLYPH = {"active": (28, 28, 30), "inactive": (150, 150, 156)}
HOVER = (229, 229, 229)
PRESS = (204, 204, 204)
CLOSE_HOVER = (196, 43, 28)
CLOSE_PRESS = (200, 60, 48)


def solid(w, h, color, edge=None, edges=""):
    img = Image.new("RGBA", (w, h), color + (255,))
    if edge:
        d = ImageDraw.Draw(img)
        if "l" in edges:
            d.line([(0, 0), (0, h - 1)], fill=edge + (255,))
        if "r" in edges:
            d.line([(w - 1, 0), (w - 1, h - 1)], fill=edge + (255,))
        if "t" in edges:
            d.line([(0, 0), (w - 1, 0)], fill=edge + (255,))
        if "b" in edges:
            d.line([(0, h - 1), (w - 1, h - 1)], fill=edge + (255,))
    return img


def glyph(kind, color, d, cx, cy):
    s = 5  # half size of the 10px glyph
    c = color + (255,)
    if kind == "hide":
        d.line([(cx - s, cy), (cx + s, cy)], fill=c)
    elif kind == "maximize":
        d.rectangle([cx - s, cy - s, cx + s, cy + s], outline=c)
    elif kind == "maximize-toggled":
        d.rectangle([cx - s + 2, cy - s, cx + s, cy + s - 2], outline=c)
        d.rectangle([cx - s, cy - s + 2, cx + s - 2, cy + s], outline=c, fill=None)
    elif kind == "close":
        # anti-aliased X: draw 4x and scale down
        big = Image.new("RGBA", (40, 40), (0, 0, 0, 0))
        bd = ImageDraw.Draw(big)
        bd.line([(0, 0), (39, 39)], fill=c, width=4)
        bd.line([(0, 39), (39, 0)], fill=c, width=4)
        return big.resize((11, 11), Image.LANCZOS)
    return None


def button(kind, state):
    """state: active, inactive, prelight, pressed"""
    base = "inactive" if state == "inactive" else "active"
    bg = TITLE[base]
    fg = GLYPH[base]
    if state == "prelight":
        bg, fg = (CLOSE_HOVER, (255, 255, 255)) if kind == "close" else (HOVER, fg)
    elif state == "pressed":
        bg, fg = (CLOSE_PRESS, (255, 255, 255)) if kind == "close" else (PRESS, fg)
    img = solid(BW, H, bg, EDGE[base], "t")
    d = ImageDraw.Draw(img)
    cx, cy = BW // 2, H // 2
    x = glyph(kind, fg, d, cx, cy)
    if x is not None:
        img.alpha_composite(x, (cx - 5, cy - 5))
    return img


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for st in ("active", "inactive"):
        t, e = TITLE[st], EDGE[st]
        for i in range(1, 6):
            solid(8, H, t, e, "t").save(OUT / f"title-{i}-{st}.png")
        solid(BORDER, H, t, e, "lt").save(OUT / f"top-left-{st}.png")
        solid(BORDER, H, t, e, "rt").save(OUT / f"top-right-{st}.png")
        solid(BORDER, 16, t, e, "l").save(OUT / f"left-{st}.png")
        solid(BORDER, 16, t, e, "r").save(OUT / f"right-{st}.png")
        solid(16, BORDER, t, e, "b").save(OUT / f"bottom-{st}.png")
        solid(BORDER, BORDER, t, e, "lb").save(OUT / f"bottom-left-{st}.png")
        solid(BORDER, BORDER, t, e, "rb").save(OUT / f"bottom-right-{st}.png")
        # app icon button: plain background, xfwm draws the window icon on top
        for s2 in ((st,) if st == "inactive" else ("active", "pressed")):
            solid(30, H, t, e, "t").save(OUT / f"menu-{s2}.png")
        for k in ("shade", "stick"):
            for s2 in ((st,) if st == "inactive" else ("active", "pressed")):
                solid(8, H, t, e, "t").save(OUT / f"{k}-{s2}.png")
    for kind in ("hide", "maximize", "maximize-toggled", "close"):
        for state in ("active", "inactive", "prelight", "pressed"):
            button(kind, state).save(OUT / f"{kind}-{state}.png")
    (OUT / "themerc").write_text(
        "# ValoLinux xfwm4 theme (generated by tools/make-xfwm-theme.py)\n"
        "button_offset=0\nbutton_spacing=0\nshow_app_icon=true\nfull_width_title=true\n"
        "title_shadow_active=false\ntitle_shadow_inactive=false\n"
        "title_horizontal_offset=6\ntitle_vertical_offset_active=1\ntitle_vertical_offset_inactive=1\n"
        "active_text_color=#1b1b1d\ninactive_text_color=#8b8b90\n"
        "shadow_delta_height=4\nshadow_delta_width=4\nshadow_delta_x=0\nshadow_delta_y=-2\nshadow_opacity=35\n"
    )
    print("written to", OUT)


if __name__ == "__main__":
    main()
